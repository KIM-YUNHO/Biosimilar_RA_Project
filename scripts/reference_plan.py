"""Write config/reference_docs.yaml: which reference-product documents to process and the
purposes each serves (see src/ra_prep/reference.py). Needs the program's EMA procedural-steps
documents to be preprocessed first.

  python scripts/reference_plan.py --program stelara
  python -m ra_prep run --doc-id ... (ids listed under process:)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ra_prep.cli import DEFAULT_DB, _store  # noqa: E402
from ra_prep.reference import load_blocks, reference_plan  # noqa: E402
from ra_prep.store import PrepDocumentRow  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--program", default="stelara")
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--out", default=str(ROOT / "config" / "reference_docs.yaml"))
    a = ap.parse_args()
    from ra_ingest.db import DocumentRow
    from sqlalchemy import select

    st = _store(a.db)
    with st.session() as s:
        steps = s.scalars(select(DocumentRow.id).where(DocumentRow.program_id == a.program,
                                                       DocumentRow.doc_type == "procedural_steps")).all()
        paths = [s.scalar(select(PrepDocumentRow.output_path).where(
            PrepDocumentRow.document_id == i, PrepDocumentRow.status == "ok")) for i in steps]
        missing = [i for i, p in zip(steps, paths) if not p]
        if missing:
            raise SystemExit(f"preprocess the procedural-steps documents first: {missing}")
        plan = reference_plan(s, a.program, [load_blocks(p) for p in paths])

    doc = {
        "program": a.program,
        "note": "Generated by scripts/reference_plan.py from the EMA procedural-steps record. "
                "Purposes: baseline_trials, indication_history, reference_label. "
                "Documents with no purpose are not processed.",
        "process": [x for x in plan if x["purposes"]],
        "not_processed": [x for x in plan if not x["purposes"]],
    }
    Path(a.out).write_text(yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")
    print(f"{len(doc['process'])} to process, {len(doc['not_processed'])} not processed -> {a.out}")
    for x in doc["not_processed"]:
        print("  skip", x["doc_id"], x["doc_type"], x["reason"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
